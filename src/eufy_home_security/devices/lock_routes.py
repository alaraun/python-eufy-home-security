"""Which lock command form a lock takes: the eufy app's rule over its per-model lock data.

Data: ``_lock_routes_data.py``, generated by ``scripts/gen_lock_routes.py`` from the app's
per-model lock configuration. Rule (declared, eufy app; docs/protocol/locks.md § Routes):

1. The product's rows: a row whose serial character matches (``index:char``: the serial's
   character at that index) wins over the plain row (the app tells T8520 variants apart
   by the 7th serial character this way).
2. MQTT when the row's rule is ``always``, or ``standalone`` and the lock is not behind a
   station (its station serial is empty or its own).
3. Else the row's P2P form: ``1940`` (the HKDF variant when the row carries firmware
   thresholds and both the lock's main and Wi-Fi firmware reach them, compared as the
   app's Remote Config does), ``1961`` or ``1961-plain``, ``1930`` (the ECDH variant when
   the row names a parameter and the lock reports it as ``"1"``), or ``1911``.

Pure functions over package data; no I/O.
"""

from __future__ import annotations

from collections.abc import Mapping
from enum import StrEnum
from typing import Final

from ._lock_routes_data import LOCK_ROUTES
from .versions import remote_version_at_least


class LockForm(StrEnum):
    """A lock command form (docs/protocol/locks.md)."""

    P2P_1940 = "p2p_1940"
    """cm2 frame in 1940 through-data, key from the user id and a time value."""
    P2P_1940_HKDF = "p2p_1940_hkdf"
    """The same with an HKDF key and a sealed time field."""
    P2P_1961 = "p2p_1961"
    """1961 JSON, AES under a random key wrapped by ECIES with the lock's public key."""
    P2P_1961_PLAIN = "p2p_1961_plain"
    """1961 JSON, plain."""
    P2P_1930 = "p2p_1930"
    """Anker cm frame in 1930 through-data, key wrapped by ECIES."""
    P2P_1930_ECDH = "p2p_1930_ecdh"
    """The same keyed by ECDH with the lock's ECDH public key."""
    P2P_1911 = "p2p_1911"
    """A BLE frame through the station (1911); no codec in this library."""
    MQTT = "mqtt"
    """The cm2 frame over the eufy cloud's MQTT broker; no transport in this library."""


P2P_FORMS: Final = frozenset({"1940", "1961", "1961-plain", "1930", "1911"})
"""The P2P form names the generated table uses."""
MQTT_RULES: Final = frozenset({"always", "standalone", "never"})
"""The MQTT rules the generated table uses."""

_PLAIN_FORMS: Final = {
    "1940": LockForm.P2P_1940,
    "1961": LockForm.P2P_1961,
    "1961-plain": LockForm.P2P_1961_PLAIN,
    "1930": LockForm.P2P_1930,
    "1911": LockForm.P2P_1911,
}
_PRODUCT_LEN: Final = 5


def _row(
    serial: str,
) -> tuple[str, str | None, str, int | None, tuple[str, str] | None] | None:
    rows = LOCK_ROUTES.get(serial[:_PRODUCT_LEN])
    if not rows:
        return None
    for row in rows[1:]:
        index_text, char = row[0].split(":", 1)
        index = int(index_text)
        if len(serial) > index and serial[index] == char:
            return row
    return rows[0]


def lock_route(
    serial: str,
    *,
    behind_station: bool,
    main_sw_version: str = "",
    sec_sw_version: str = "",
    params: Mapping[int, object] | None = None,
) -> LockForm | None:
    """The form a lock or unlock command to the lock ``serial`` takes, or None.

    ``behind_station``: the lock's station serial is set and not its own.
    ``main_sw_version``/``sec_sw_version``: the lock's main and Wi-Fi firmware (the cloud
    record's ``main_sw_version``/``sec_sw_version``; ``""`` when unknown, which reaches
    no threshold). ``params``: the lock's parameters by id (merged station and cloud
    values). None for a product without lock route data (not a lock, or a keypad).
    """
    row = _row(serial)
    if row is None:
        return None
    _, form, mqtt, ecdh_param, hkdf = row
    if mqtt == "always" or (mqtt == "standalone" and not behind_station):
        return LockForm.MQTT
    if form is None:
        return None
    if form == "1940" and hkdf is not None:
        main, wifi = hkdf
        if remote_version_at_least(main_sw_version, main) and remote_version_at_least(
            sec_sw_version, wifi
        ):
            return LockForm.P2P_1940_HKDF
    if form == "1930" and ecdh_param is not None:
        value = (params or {}).get(ecdh_param)
        if value is not None and str(value) == "1":
            return LockForm.P2P_1930_ECDH
    return _PLAIN_FORMS[form]
