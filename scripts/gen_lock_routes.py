"""Generate ``devices/_lock_routes_data.py``: the lock command form each lock product takes.

Input: the per-model lock configuration extracted from the eufy app (a private
``lock_routes.json``, docs/how-to/regenerate-models.md; per app model: the serial prefix and an
optional serial character that picks the model, the P2P protocol service, the MQTT rule,
whether the 1961 command goes plain, the lock parameter that switches the 1930 frame to
ECDH, and the Remote Config keys and default thresholds of the HKDF key), plus a Remote
Config fetch (``{"template_version", "entries"}``) whose entries replace a default when
they name its key. The rule that reads the table is
:mod:`eufy_home_security.devices.lock_routes`. A P2P service or MQTT rule this rule does
not know stops the generator. Runs on a maintainer host only.

    gen_lock_routes.py [--routes FILE] [--remote-config FILE] [--out FILE] [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from eufy_home_security.devices.lock_routes import MQTT_RULES, P2P_FORMS

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ROUTES = ROOT / ".work" / "tools" / "data" / "lock_routes.json"
DEFAULT_REMOTE_CONFIG = ROOT / ".work" / "tools" / "data" / "firebase_rc_EE.json"
DEFAULT_OUT = ROOT / "src" / "eufy_home_security" / "devices" / "_lock_routes_data.py"

# The app's P2P protocol service -> the form the library names it by.
_SERVICES = {
    "Anker_Company": "1940",
    "Anker": "1961",
    "AnkerBleV12": "1930",
    "Station": "1911",
    None: None,
}

type Row = tuple[str, str | None, str, int | None, tuple[str, str] | None]


def row(model: str, entry: Mapping[str, Any], remote: Mapping[str, Any]) -> Row:
    """One model's table row: serial character, P2P form, MQTT rule, ECDH param, HKDF."""
    service = entry.get("p2p")
    if service not in _SERVICES:
        raise SystemExit(f"{model}: P2P service {service!r} unknown")
    form = _SERVICES[service]
    if form == "1961" and entry.get("plain_1961"):
        form = "1961-plain"
    if form not in P2P_FORMS and form is not None:
        raise SystemExit(f"{model}: form {form!r} unknown to the rule")
    mqtt = entry.get("mqtt")
    if mqtt not in MQTT_RULES:
        raise SystemExit(f"{model}: MQTT rule {mqtt!r} unknown")
    serial_char = entry.get("serial_char")
    char = "" if serial_char is None else f"{int(serial_char[0])}:{serial_char[1]}"
    hkdf = entry.get("hkdf")
    thresholds = None
    if hkdf is not None:
        thresholds = (
            str(remote.get(hkdf["main_key"], hkdf["main"])),
            str(remote.get(hkdf["wifi_key"], hkdf["wifi"])),
        )
    param = entry.get("ecdh_param")
    return (char, form, mqtt, None if param is None else int(param), thresholds)


def generate(routes: Path, remote_config: Path) -> dict[str, list[Row]]:
    """Per product code, its rows: the plain serial first, then each serial character."""
    data = json.loads(routes.read_text(encoding="utf-8"))
    remote: Mapping[str, Any] = {}
    if remote_config.is_file():
        remote = json.loads(remote_config.read_text(encoding="utf-8")).get("entries") or {}
    table: dict[str, list[Row]] = {}
    for model, entry in sorted(data["models"].items()):
        built = row(model, entry, remote)
        if built[1] is None and built[2] == "never":
            continue  # no lock command route (keypads)
        table.setdefault(entry["prefix"], []).append(built)
    for code, rows in table.items():
        rows.sort(key=lambda r: r[0])
        if rows[0][0]:
            raise SystemExit(f"{code}: no row for the plain serial")
    return dict(sorted(table.items()))


def _row_text(row: Row) -> str:
    char, form, mqtt, param, hkdf = row
    thresholds = "None" if hkdf is None else f"({json.dumps(hkdf[0])}, {json.dumps(hkdf[1])})"
    form_text = "None" if form is None else json.dumps(form)
    return f"({json.dumps(char)}, {form_text}, {json.dumps(mqtt)}, {param}, {thresholds})"


def render(table: Mapping[str, list[Row]]) -> str:
    """The module text."""
    lines = [
        '"""Generated by scripts/gen_lock_routes.py from the eufy app\'s lock configuration;',
        'do not edit. Per product code, rows of (serial character ``index:char`` or ``""`` for',
        "every other serial, P2P form, MQTT rule, ECDH parameter, HKDF firmware thresholds",
        '``(main, wifi)``)."""',
        "",
        "from typing import Final",
        "",
        "LOCK_ROUTES: Final[",
        "    dict[str, tuple[tuple[str, str | None, str, int | None, tuple[str, str] | None], ...]]",
        "] = {" if table else "] = {}",
    ]
    for code, rows in table.items():
        texts = [_row_text(r) for r in rows]
        if len(texts) == 1:  # the formatter's layout: one row inline, several exploded
            lines.append(f"    {json.dumps(code)}: ({texts[0]},),")
            continue
        lines.append(f"    {json.dumps(code)}: (")
        lines.extend(f"        {text}," for text in texts)
        lines.append("    ),")
    if table:
        lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate devices/_lock_routes_data.py.")
    parser.add_argument("--routes", type=Path, default=DEFAULT_ROUTES)
    parser.add_argument("--remote-config", type=Path, default=DEFAULT_REMOTE_CONFIG)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="compare with --out, write nothing")
    args = parser.parse_args(argv)
    text = render(generate(args.routes, args.remote_config))
    if args.check:
        same = args.out.exists() and args.out.read_text(encoding="utf-8") == text
        print("up to date" if same else f"{args.out} differs")
        return 0 if same else 1
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
