"""Generate ``devices/_webrtc_routing_data.py``: the thing-description inputs of the WebRTC route.

For every cached product whose thing description declares an ``is_connect_webrtc*``
property, the file records each such property in thing-description order: its
identifier, its default value as the eufy app reads it (an enum's default entry, else
``defaultValue``, else empty), and its ``available_conditions`` and ``read_conditions``
as lists of condition groups of ``[type, qualifier, value]``. It also records the
thing-SDK version the app compares ``sdk_version`` conditions with. The rule that reads
them is :mod:`eufy_home_security.devices.webrtc`. A condition type that rule does not
evaluate, or a pattern Python cannot compile, stops the generator. Runs on a maintainer
host only.

The table is a Python module, so reading it is an import and never file I/O on the
event loop.

    gen_webrtc_routing.py [--cache DIR] [--out FILE] [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from eufy_home_security.devices.webrtc import CONDITION_TYPES, ROUTE_PROPERTY

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CACHE = ROOT / ".work" / "cache" / "things_all"
DEFAULT_OUT = ROOT / "src" / "eufy_home_security" / "devices" / "_webrtc_routing_data.py"
TD_FILE = "td.json"
THING_SDK_VERSION = "2.3.1.2"  # the thing-SDK version of the app build the cache holds

type Condition = list[str]
type Conditions = list[list[Condition]]
type Prop = tuple[str, str, Conditions, Conditions]


def default_value(prop: Mapping[str, Any]) -> str:
    """The value the app reads when nothing reports one: the enum entry marked default
    (``""`` when none is), else ``defaultValue``, else ``""``."""
    specs = (prop.get("data_type") or {}).get("specs") or {}
    enums = specs.get("eunmList") or specs.get("enumList")
    if enums:
        found = next((e for e in enums if e.get("isDefault") == 1), None)
        return "" if found is None else str(found.get("value") or "")
    value = specs.get("defaultValue")
    if value is not None and not isinstance(value, str):
        raise SystemExit(f"{prop.get('identifier')}: defaultValue {value!r} is not text")
    return value or ""


def conditions(code: str, prop: Mapping[str, Any], key: str) -> Conditions:
    """``prop[key]`` as condition groups; stops on a type the rule does not evaluate."""
    groups: Conditions = []
    for group in (prop.get(key) or {}).get("condition_list") or []:
        out: list[Condition] = []
        for cond in group.get("conditions") or []:
            kind = cond.get("type", "")
            if kind not in CONDITION_TYPES:
                raise SystemExit(f"{code} {prop.get('identifier')}: condition type {kind!r}")
            qualifier, value = str(cond.get("qualifier") or ""), str(cond.get("value") or "")
            if qualifier == "RE" or kind in ("device_sn", "parent_sn"):
                re.compile(value)
            out.append([kind, qualifier, value])
        groups.append(out)
    return groups


def generate(cache: Path) -> dict[str, list[Prop]]:
    """Per product code, its routing properties in thing-description order."""
    table: dict[str, list[Prop]] = {}
    for path in sorted(cache.glob(f"*/{TD_FILE}")):
        code = path.parent.name
        td = json.loads(path.read_text(encoding="utf-8"))
        props = [
            (
                p["identifier"],
                default_value(p),
                conditions(code, p, "available_conditions"),
                conditions(code, p, "read_conditions"),
            )
            for p in td.get("properties") or []
            if str(p.get("identifier", "")).startswith(ROUTE_PROPERTY)
        ]
        if props:
            table[code] = props
    return table


def _text(value: str) -> str:
    """A string literal as the formatter writes it (single quotes around double ones)."""
    if '"' in value and "'" not in value and "\\" not in value:
        return f"'{value}'"
    return json.dumps(value, ensure_ascii=False)


def _conditions(groups: Conditions, indent: str) -> list[str]:
    """``groups`` as source lines, one condition per line, exploded by trailing commas."""
    if not groups:
        return [f"{indent}[],"]
    lines = [f"{indent}["]
    for group in groups:
        lines.append(f"{indent}    [")
        lines.extend(f"{indent}        [{', '.join(_text(v) for v in c)}]," for c in group)
        lines.append(f"{indent}    ],")
    lines.append(f"{indent}],")
    return lines


def render(table: Mapping[str, list[Prop]]) -> str:
    """The module text: one line per identifier, default and condition."""
    lines = [
        '"""Generated by scripts/gen_webrtc_routing.py from the eufy app\'s thing descriptions;',
        "do not edit. Per product code, each ``is_connect_webrtc*`` property in",
        "thing-description order: identifier, default value, available conditions, read",
        "conditions (groups of ``[type, qualifier, value]``); and the thing-SDK version",
        'the app compares ``sdk_version`` conditions with."""',
        "",
        "from typing import Final",
        "",
        f"THING_SDK_VERSION: Final = {json.dumps(THING_SDK_VERSION)}",
        "",
        "ROUTE_PROPERTIES: Final[",
        "    dict[str, list[tuple[str, str, list[list[list[str]]], list[list[list[str]]]]]]",
        "] = {",
    ]
    for code, props in table.items():
        lines.append(f"    {json.dumps(code)}: [")
        for identifier, default, available, read in props:
            lines += [
                "        (",
                f"            {_text(identifier)},",
                f"            {_text(default)},",
            ]
            lines += _conditions(available, " " * 12) + _conditions(read, " " * 12)
            lines.append("        ),")
        lines.append("    ],")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate devices/_webrtc_routing_data.py.")
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="compare with --out, write nothing")
    args = parser.parse_args(argv)
    text = render(generate(args.cache))
    if args.check:
        same = args.out.exists() and args.out.read_text(encoding="utf-8") == text
        print("up to date" if same else f"{args.out} differs")
        return 0 if same else 1
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
